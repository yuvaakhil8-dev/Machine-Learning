def compute_class_separability(
    X: pd.DataFrame,
    y: pd.Series,
    visual_columns: list[str],
) -> dict[str, float | str]:
    numeric_columns = visual_columns
    if not numeric_columns:
        return {"separability_note": "No numeric features available for separability analysis."}

    numeric = X[numeric_columns].fillna(0)
    safe_vectors = numeric[y == 0]
    unsafe_vectors = numeric[y == 1]

    if safe_vectors.empty or unsafe_vectors.empty:
        return {"separability_note": "Both classes are required for separability analysis."}

    safe_centroid = safe_vectors.mean(axis=0).to_numpy()
    unsafe_centroid = unsafe_vectors.mean(axis=0).to_numpy()

    inter_class_distance = float(np.linalg.norm(safe_centroid - unsafe_centroid))
    intra_safe = float(np.linalg.norm(safe_vectors.to_numpy() - safe_centroid, axis=1).mean())
    intra_unsafe = float(np.linalg.norm(unsafe_vectors.to_numpy() - unsafe_centroid, axis=1).mean())
    mean_intra_class_spread = (intra_safe + intra_unsafe) / 2.0

    return {
        "inter_class_distance": round(inter_class_distance, 4),
        "mean_intra_class_spread": round(mean_intra_class_spread, 4),
        "separability_verdict": "good"
        if inter_class_distance > mean_intra_class_spread
        else "weak",
    }


def run_knn_sweep(
    *,
    X_train: pd.DataFrame,
    X_test: pd.DataFrame,
    y_train: pd.Series,
    y_test: pd.Series,
    preprocessor: ColumnTransformer,
    output_dir: Path,
    random_state: int,
) -> pd.DataFrame:
    fitted_preprocessor = clone(preprocessor)
    X_train_features = fitted_preprocessor.fit_transform(X_train, y_train)
    X_test_features = fitted_preprocessor.transform(X_test)

    feature_count = X_train_features.shape[1]
    sample_count = X_train_features.shape[0]
    max_components = min(50, feature_count - 1, sample_count - 1)

    if max_components >= 2:
        reducer = TruncatedSVD(n_components=max_components, random_state=random_state)
        X_train_ready = reducer.fit_transform(X_train_features)
        X_test_ready = reducer.transform(X_test_features)
    else:
        X_train_ready = X_train_features.toarray() if hasattr(X_train_features, "toarray") else X_train_features
        X_test_ready = X_test_features.toarray() if hasattr(X_test_features, "toarray") else X_test_features

    scaler = StandardScaler()
    X_train_ready = scaler.fit_transform(X_train_ready)
    X_test_ready = scaler.transform(X_test_ready)

    rows: list[dict[str, float | int]] = []

    for k in range(1, 12):
        model = KNeighborsClassifier(n_neighbors=k)
        model.fit(X_train_ready, y_train)
        y_pred = model.predict(X_test_ready)
        rows.append(
            {
                "k": k,
                "accuracy": round(accuracy_score(y_test, y_pred), 4),
                "f1_score": round(f1_score(y_test, y_pred, zero_division=0), 4),
            }
        )

    results = pd.DataFrame(rows)
    results.to_csv(output_dir / "knn_results.csv", index=False)

    best_row = results.sort_values(["accuracy", "f1_score"], ascending=False).iloc[0]
    best_k = int(best_row["k"])

    best_artifact = {
        "preprocessor": fitted_preprocessor,
        "scaler": scaler,
        "model": KNeighborsClassifier(n_neighbors=best_k).fit(X_train_ready, y_train),
        "used_svd": max_components >= 2,
        "svd": reducer if max_components >= 2 else None,
    }
    joblib.dump(best_artifact, output_dir / "best_knn_model.joblib")

    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(results["k"], results["accuracy"], marker="o")
    ax.set_xlabel("k")
    ax.set_ylabel("Accuracy")
    ax.set_title("KNN: k vs Accuracy")
    ax.set_xticks(results["k"])
    ax.grid(True, linestyle="--", alpha=0.4)
    fig.tight_layout()
    fig.savefig(output_dir / "knn_k_vs_accuracy.png")
    plt.close(fig)

    return results


def main() -> None:
    args = parse_args()
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    df = ensure_required_columns(pd.read_csv(args.csv))
    df.attrs["source_csv"] = args.csv
    visual_columns = detect_feature_groups(df)

    metadata_columns = [column for column in ("video_name", "video_path", "class_name") if column in df.columns]
    X = df.drop(columns=["label"])
    y = df["label"]

    X_train, X_test, y_train, y_test = train_test_split(
        X,
        y,
        test_size=args.test_size,
        stratify=y,
        random_state=args.random_state,
    )

    split_summary = {
        "train_samples": int(len(X_train)),
        "test_samples": int(len(X_test)),
        "safe_train": int((y_train == 0).sum()),
        "unsafe_train": int((y_train == 1).sum()),
        "safe_test": int((y_test == 0).sum()),
        "unsafe_test": int((y_test == 1).sum()),
    }
    (output_dir / "split_summary.json").write_text(
        json.dumps(split_summary, indent=2),
        encoding="utf-8",
    )

    experiments: list[tuple[str, Pipeline]] = []

    model_suite = build_model_suite(args.random_state)

    if visual_columns:
        visual_only_preprocessor = build_numeric_only_preprocessor(visual_columns)
        experiments.extend(
            [
                (
                    "phase1_visual_logistic",
                    Pipeline(steps=[("preprocessor", visual_only_preprocessor), ("model", model_suite["logistic_regression"])]),
                ),
                (
                    "phase2_visual_decision_tree",
                    Pipeline(steps=[("preprocessor", visual_only_preprocessor), ("model", model_suite["decision_tree"])]),
                ),
                (
                    "phase3_visual_random_forest",
                    Pipeline(steps=[("preprocessor", visual_only_preprocessor), ("model", model_suite["random_forest"])]),
                ),
                (
                    "phase4_visual_svm",
                    Pipeline(steps=[("preprocessor", visual_only_preprocessor), ("model", model_suite["svm_rbf"])]),
                ),
                (
                    "phase5_visual_knn",
                    Pipeline(steps=[("preprocessor", visual_only_preprocessor), ("model", model_suite["knn"])]),
                ),
                (
                    "phase6_visual_naive_bayes",
                    Pipeline(steps=[("preprocessor", visual_only_preprocessor), ("model", model_suite["naive_bayes"])]),
                ),
                (
                    "phase7_visual_adaboost",
                    Pipeline(steps=[("preprocessor", visual_only_preprocessor), ("model", model_suite["adaboost"])]),
                ),
                (
                    "phase8_visual_xgboost",
                    Pipeline(steps=[("preprocessor", visual_only_preprocessor), ("model", model_suite["xgboost"])]),
                ),
                (
                    "phase9_visual_mlp_classifier",
                    Pipeline(steps=[("preprocessor", visual_only_preprocessor), ("model", model_suite["mlp_classifier"])]),
                ),
                (
                    "phase10_visual_stacking_classifier",
                    Pipeline(
                        steps=[
                            ("preprocessor", visual_only_preprocessor),
                            ("model", build_stacking_classifier(args.random_state)),
                        ]
                    ),
                ),
            ]
        )

    if not experiments:
        raise SystemExit("No valid experiments could be built from the provided CSV.")

    metrics_rows: list[dict[str, float | str]] = []
    for name, estimator in experiments:
        metrics_rows.append(
            evaluate_pipeline(
                name=name,
                estimator=estimator,
                X_train=X_train,
                X_test=X_test,
                y_train=y_train,
                y_test=y_test,
                output_dir=output_dir,
            )
        )

    metrics_df = pd.DataFrame(metrics_rows).sort_values("test_accuracy", ascending=False)
    metrics_df.to_csv(output_dir / "metrics_summary.csv", index=False)

    preprocessor_for_knn = build_numeric_only_preprocessor(visual_columns)
    knn_results = run_knn_sweep(
        X_train=X_train,
        X_test=X_test,
        y_train=y_train,
        y_test=y_test,
        preprocessor=preprocessor_for_knn,
        output_dir=output_dir,
        random_state=args.random_state,
    )

    analysis = compute_class_separability(X, y, visual_columns)
    analysis["best_knn_k"] = int(knn_results.sort_values(["accuracy", "f1_score"], ascending=False).iloc[0]["k"])
    analysis["best_knn_accuracy"] = float(knn_results["accuracy"].max())
    (output_dir / "analysis_summary.json").write_text(
        json.dumps(analysis, indent=2),
        encoding="utf-8",
    )

    write_phase1_report(
        df=df,
        visual_columns=visual_columns,
        metrics_df=metrics_df,
        analysis=analysis,
        output_dir=output_dir,
    )

    if metadata_columns:
        test_export = X_test[metadata_columns].copy()
        test_export["true_label"] = y_test.to_numpy()
        test_export.to_csv(output_dir / "test_split_metadata.csv", index=False)

    print("Finished running experiments.")
    print(metrics_df.to_string(index=False))
    print()
    print("Best KNN result:")
    print(knn_results.sort_values(["accuracy", "f1_score"], ascending=False).head(1).to_string(index=False))


if __name__ == "__main__":
    main()
