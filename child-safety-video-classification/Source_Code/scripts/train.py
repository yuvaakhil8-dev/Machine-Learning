def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run phased experiments for multi-model child-safety video classification."
    )
    parser.add_argument(
        "--csv",
        default="Feature_Files/video_features_advanced.csv",
        help="Video-only feature CSV generated by build_video_only_features.py.",
    )
    parser.add_argument(
        "--output-dir",
        default="Models/artifacts_phase1",
        help="Directory where reports, plots, and models will be saved.",
    )
    parser.add_argument(
        "--test-size",
        type=float,
        default=0.3,
        help="Test split ratio.",
    )
    parser.add_argument(
        "--random-state",
        type=int,
        default=42,
        help="Random seed for reproducibility.",
    )
    return parser.parse_args()


def ensure_required_columns(df: pd.DataFrame) -> pd.DataFrame:
    prepared = df.copy()

    if "label" not in prepared.columns:
        raise ValueError("Input CSV must contain a 'label' column.")

    return prepared


def detect_feature_groups(df: pd.DataFrame) -> list[str]:
    excluded = {
        "label",
        "video_name",
        "video_path",
        "class_name",
    }
    visual_columns = [
        column
        for column in df.columns
        if column not in excluded and pd.api.types.is_numeric_dtype(df[column])
    ]
    return visual_columns


def build_numeric_only_preprocessor(columns: list[str]) -> ColumnTransformer:
    return ColumnTransformer(
        transformers=[
            (
                "numeric",
                Pipeline(
                    steps=[
                        ("imputer", SimpleImputer(strategy="constant", fill_value=0)),
                        ("scaler", StandardScaler()),
                    ]
                ),
                columns,
            )
        ],
        remainder="drop",
    )


def build_xgboost(random_state: int) -> XGBClassifier:
    return XGBClassifier(
        n_estimators=250,
        max_depth=5,
        learning_rate=0.05,
        subsample=0.9,
        colsample_bytree=0.9,
        eval_metric="logloss",
        random_state=random_state,
    )


def build_model_suite(random_state: int) -> dict[str, object]:
    return {
        "logistic_regression": LogisticRegression(max_iter=3000, random_state=random_state),
        "decision_tree": DecisionTreeClassifier(
            max_depth=8,
            min_samples_leaf=3,
            class_weight="balanced",
            random_state=random_state,
        ),
        "random_forest": RandomForestClassifier(
            n_estimators=300,
            max_depth=None,
            min_samples_leaf=2,
            class_weight="balanced",
            random_state=random_state,
            n_jobs=-1,
        ),
        "svm_rbf": SVC(
            kernel="rbf",
            C=2.0,
            gamma="scale",
            probability=True,
            class_weight="balanced",
            random_state=random_state,
        ),
        "knn": KNeighborsClassifier(n_neighbors=7),
        "naive_bayes": GaussianNB(),
        "adaboost": AdaBoostClassifier(n_estimators=150, learning_rate=0.5, random_state=random_state),
        "xgboost": build_xgboost(random_state),
        "mlp_classifier": MLPClassifier(
            hidden_layer_sizes=(64, 32),
            activation="relu",
            alpha=0.001,
            learning_rate_init=0.001,
            early_stopping=True,
            validation_fraction=0.15,
            max_iter=600,
            random_state=random_state,
        ),
    }


def build_stacking_classifier(random_state: int) -> StackingClassifier:
    return StackingClassifier(
        estimators=[
            (
                "rf",
                RandomForestClassifier(
                    n_estimators=250,
                    min_samples_leaf=2,
                    class_weight="balanced",
                    random_state=random_state,
                    n_jobs=-1,
                ),
            ),
            (
                "svm",
                SVC(
                    kernel="rbf",
                    C=2.0,
                    gamma="scale",
                    probability=True,
                    class_weight="balanced",
                    random_state=random_state,
                ),
            ),
            ("xgb", build_xgboost(random_state)),
            (
                "mlp",
                MLPClassifier(
                    hidden_layer_sizes=(64, 32),
                    activation="relu",
                    alpha=0.001,
                    learning_rate_init=0.001,
                    early_stopping=True,
                    validation_fraction=0.15,
                    max_iter=600,
                    random_state=random_state,
                ),
            ),
        ],
        final_estimator=LogisticRegression(max_iter=3000, random_state=random_state),
        stack_method="predict_proba",
        cv=5,
        n_jobs=-1,
        passthrough=False,
    )


def save_confusion_matrix(matrix: np.ndarray, labels: list[str], title: str, path: Path) -> None:
    fig, ax = plt.subplots(figsize=(5, 4))
    im = ax.imshow(matrix, cmap="Blues")
    ax.set_xticks(range(len(labels)))
    ax.set_yticks(range(len(labels)))
    ax.set_xticklabels(labels)
    ax.set_yticklabels(labels)
    ax.set_xlabel("Predicted label")
    ax.set_ylabel("True label")
    ax.set_title(title)

    for i in range(matrix.shape[0]):
        for j in range(matrix.shape[1]):
            ax.text(j, i, matrix[i, j], ha="center", va="center", color="black")

    fig.colorbar(im, ax=ax)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def describe_fit(train_accuracy: float, test_accuracy: float) -> str:
    gap = train_accuracy - test_accuracy
    if train_accuracy >= 0.95 and gap >= 0.1:
        return "cv_review"
    if train_accuracy < 0.65 and test_accuracy < 0.65:
        return "low_fit"
    if abs(gap) <= 0.05:
        return "stable_fit"
    return "moderate_gap"


def evaluate_pipeline(
    *,
    name: str,
    estimator: Pipeline,
    X_train: pd.DataFrame,
    X_test: pd.DataFrame,
    y_train: pd.Series,
    y_test: pd.Series,
    output_dir: Path,
) -> dict[str, float | str]:
    model = clone(estimator)
    model.fit(X_train, y_train)

    train_pred = model.predict(X_train)
    test_pred = model.predict(X_test)
    test_proba = model.predict_proba(X_test) if hasattr(model, "predict_proba") else None

    train_accuracy = accuracy_score(y_train, train_pred)
    test_accuracy = accuracy_score(y_test, test_pred)
    precision = precision_score(y_test, test_pred, zero_division=0)
    recall = recall_score(y_test, test_pred, zero_division=0)
    f1 = f1_score(y_test, test_pred, zero_division=0)
    matrix = confusion_matrix(y_test, test_pred)

    predictions = pd.DataFrame(
        {
            "true_label": y_test.to_numpy(),
            "predicted_label": test_pred,
        }
    )
    predictions.to_csv(output_dir / f"{name}_predictions.csv", index=False)

    save_confusion_matrix(
        matrix,
        labels=["safe", "unsafe"],
        title=f"{name.replace('_', ' ').title()} Confusion Matrix",
        path=output_dir / f"{name}_confusion_matrix.png",
    )

    joblib.dump(model, output_dir / f"{name}_model.joblib")

    metrics = {
        "phase": name,
        "train_accuracy": round(train_accuracy, 4),
        "test_accuracy": round(test_accuracy, 4),
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1_score": round(f1, 4),
        "fit_status": describe_fit(train_accuracy, test_accuracy),
    }
    advanced = compute_advanced_metrics(y_test, test_pred, test_proba)
    for key in ("specificity", "mcc", "roc_auc", "pr_auc", "log_loss"):
        if key in advanced:
            metrics[key] = advanced[key]

    (output_dir / f"{name}_classification_report.txt").write_text(
        classification_report(y_test, test_pred, target_names=["safe", "unsafe"]),
        encoding="utf-8",
    )

    return metrics


